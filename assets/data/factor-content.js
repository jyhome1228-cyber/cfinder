export const FACTOR_TOTAL = Object.values(FACTORS).reduce((sum, list) => sum + list.length, 0);
export function factorQuestions(grade) {
  if (grade !== 'middle' && grade !== 'high') throw new Error('Factor exploration is currently limited to middle and high school.');
  return Object.entries(FACTORS).flatMap(([domain, rows]) => rows.map(([factor, description], i) => {
    const text = domain === 'interest'
      ? `나는 ‘${factor}’ 관련 활동에 관심이 있다.`
      : domain === 'aptitude'
        ? `나는 ‘${factor}’을 나의 강점 중 하나라고 생각한다.`
        : `진로를 선택할 때 ‘${factor}’을 중요하게 생각한다.`;
    return Object.freeze({
      id: `${grade === 'middle' ? 'M' : 'H'}-FACTOR-${domain.toUpperCase()}-${String(i+1).padStart(2,'0')}`,
      domain, factor, description, text
    });
  }));
}
